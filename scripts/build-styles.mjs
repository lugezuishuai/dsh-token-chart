/**
 * Compile the plugin stylesheet: Tailwind (utilities) + Less (components) into
 * one real CSS artifact at `lib/token-chart.css`.
 *
 * The artifact is served by the Host half and linked by the browser half, so the
 * client bundle carries no CSS text of its own.
 */
import { execFile } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { promisify } from 'node:util'
import { gzipSync } from 'node:zlib'
import { join } from 'node:path'

const run = promisify(execFile)
const OUT = 'lib/token-chart.css'
const CACHE = 'node_modules/.cache/dtc-styles'

await mkdir(CACHE, { recursive: true })
await mkdir('lib', { recursive: true })

const bin = (name) => join('node_modules', '.bin', name)

await run(bin('tailwindcss'), ['-i', 'src/client/styles/tailwind.css', '-o', `${CACHE}/tailwind.css`, '--minify'])
await run(bin('lessc'), ['src/client/styles/index.less', `${CACHE}/less.css`])

const [tailwind, less] = await Promise.all([
  readFile(`${CACHE}/tailwind.css`, 'utf8'),
  readFile(`${CACHE}/less.css`, 'utf8'),
])
const css = `/* dsh-token-chart — Tailwind utilities + Less components. Generated by scripts/build-styles.mjs. */\n${tailwind}\n${less}\n`
await writeFile(`${OUT}.tmp`, css, 'utf8')

// Invariants: the artifact has to carry both layers, and must not smuggle a
// preflight reset into the product's page.
for (const selector of ['.dtc-table', '.dtc-page-current', '.flex', '.justify-end']) {
  if (!css.includes(selector)) {
    console.error(`build-styles: expected ${selector} in the artifact`)
    process.exit(1)
  }
}
if (/^\s*\*,\s*::?(before|after)/m.test(css) || css.includes('@layer base')) {
  console.error('build-styles: the artifact must not contain Tailwind preflight')
  process.exit(1)
}

const { rename } = await import('node:fs/promises')
await rename(`${OUT}.tmp`, OUT)
console.log(`built ${OUT}`)
console.log(`  raw ${css.length.toLocaleString('en-US')} B · gzip-1 ${gzipSync(Buffer.from(css), { level: 1 }).length.toLocaleString('en-US')} B`)
